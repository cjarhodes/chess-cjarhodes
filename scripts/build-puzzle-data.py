#!/usr/bin/env python3
"""Build puzzle-data.js from the Lichess puzzle database (CC0).

The full database is ~300 MB compressed, so this streams the first rows
(puzzle ids are random, so the head is an unbiased sample), keeps well-rated,
frequently played puzzles, and balances them across rating bands and motifs.

Usage (needs `pip install zstandard`; not part of CI):

    python3 -I scripts/build-puzzle-data.py [rows-to-scan] [per-band]

The output is deterministic for a given input sample and seed.
"""
import collections
import csv
import io
import json
import os
import random
import sys
import urllib.request

SOURCE = 'https://database.lichess.org/lichess_db_puzzle.csv.zst'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'puzzle-data.js')
SCAN = int(sys.argv[1]) if len(sys.argv) > 1 else 600000
PER_BAND = int(sys.argv[2]) if len(sys.argv) > 2 else 120
NON_MOTIFS = {
    'short', 'long', 'veryLong', 'oneMove', 'middlegame', 'endgame', 'opening',
    'advantage', 'crushing', 'equality', 'master', 'masterVsMaster', 'superGM',
}


def rows():
    import zstandard  # imported here so --help style runs work without it
    stream = urllib.request.urlopen(SOURCE)
    reader = io.TextIOWrapper(zstandard.ZstdDecompressor().stream_reader(stream), encoding='utf-8')
    for index, row in enumerate(csv.DictReader(reader)):
        if index >= SCAN:
            return
        yield row


def eligible(row):
    try:
        rating = int(row['Rating'])
        deviation = int(row['RatingDeviation'])
        popularity = int(row['Popularity'])
        plays = int(row['NbPlays'])
    except (KeyError, ValueError):
        return None
    moves = row['Moves'].split()
    # Beginner bands are sparse, so accept fewer plays there.
    min_plays = 300 if rating < 900 else 800
    if deviation > 85 or popularity < 85 or plays < min_plays:
        return None
    if len(moves) < 2 or len(moves) > 12 or len(moves) % 2:
        return None
    return [row['PuzzleId'], row['FEN'], row['Moves'], rating, row['Themes']]


def motif(themes):
    return next((t for t in themes.split() if t not in NON_MOTIFS), 'other')


def main():
    random.seed(7)
    bands = collections.defaultdict(list)
    for row in rows():
        item = eligible(row)
        if item:
            bands[max(400, min(2800, item[3] // 100 * 100))].append(item)
    picked = []
    for band in sorted(bands):
        pool = bands[band]
        random.shuffle(pool)
        by_motif = collections.defaultdict(list)
        for item in pool:
            by_motif[motif(item[4])].append(item)
        chosen = []
        while len(chosen) < PER_BAND and any(by_motif.values()):
            for key in list(by_motif):
                if by_motif[key] and len(chosen) < PER_BAND:
                    chosen.append(by_motif[key].pop())
        picked.extend(chosen)
    picked.sort(key=lambda item: (item[3], item[0]))
    with open(OUT, 'w', encoding='utf-8') as handle:
        handle.write('// Generated by scripts/build-puzzle-data.py. Do not edit by hand.\n')
        handle.write('// Source: Lichess puzzle database, https://database.lichess.org/#puzzles\n')
        handle.write('// Licence: Creative Commons CC0. Rows: [id, fen, uci moves, rating, themes].\n')
        handle.write('// The FEN is before the opponent move; the solver replies to moves[0].\n')
        handle.write('var PUZZLE_DATA = [\n')
        for item in picked:
            handle.write(json.dumps(item, separators=(',', ':')) + ',\n')
        handle.write('];\n')
        handle.write("if (typeof module !== 'undefined') module.exports = PUZZLE_DATA;\n")
    print(f'wrote {len(picked)} puzzles to {OUT}')


if __name__ == '__main__':
    main()
