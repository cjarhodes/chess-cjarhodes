#!/usr/bin/env node
// Keeps styling on the design tokens (docs/design-spec.md): colours, font
// sizes and font families come from styles/tokens.css, never raw values in
// styles.css or the markup that app scripts generate. Also checks that every
// vendored font file exists and ships with its licence.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const errors = [];

const css = read('styles.css').replace(/\/\*[\s\S]*?\*\//g, '');
const lineOf = (text, index) => text.slice(0, index).split('\n').length;

for (const m of css.matchAll(/#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?)\(/g)) {
  errors.push(`styles.css:${lineOf(css, m.index)} raw colour ${m[0]}; use a token from styles/tokens.css`);
}
for (const m of css.matchAll(/font-size:\s*([^;}]+)/g)) {
  const value = m[1].replace(/!important/, '').trim();
  const ok = /^(?:var\(--text-[a-z0-9]+\)|(?:calc|clamp|min|max)\((?:[^()]|\([^()]*\))*var\(--text-[a-z0-9]+\)(?:[^()]|\([^()]*\))*\)|inherit|1em)$/.test(value);
  if (!ok) errors.push(`styles.css:${lineOf(css, m.index)} font-size ${value}; use the --text-* scale`);
}
for (const m of css.matchAll(/font-family:\s*([^;}]+)/g)) {
  const value = m[1].replace(/!important/, '').trim();
  if (!/^(?:var\(--family-(?:ui|display|prose|mono)\)|inherit)$/.test(value)) {
    errors.push(`styles.css:${lineOf(css, m.index)} font-family ${value}; use a --family-* token`);
  }
}
const retired = css.match(/var\(--(?:font-mono|font-reading|muted|surface2|border|rule-\d|accent-dim|error|highlight|white-cat|black-cat|walnut|success-bg|error-bg)\)/g);
if (retired) errors.push(`styles.css uses retired tokens: ${[...new Set(retired)].join(', ')}`);

// Markup generated by scripts must not hard-code colours either.
for (const file of [...require('./lib/app-source').appScriptFiles(), 'growth.js', 'account-continuity.js', 'learning-transfer.js', 'opening-transfer.js', 'puzzles.js', 'puzzles-core.js', 'board-overlay.js', 'coach-overlay.js', 'shortcuts.js', 'move-flair.js', 'explore-analysis.js', 'game-archive.js', 'game-import.js', 'game-import-core.js', 'repertoire-core.js', 'clock-core.js', 'coach-clock.js', 'opponents.js', 'activity.js', 'endgames.js']) {
  const src = read(file);
  for (const m of src.matchAll(/(?:color|background|fill|stroke)\s*[:=]\s*["']?\s*#[0-9a-fA-F]{3,8}\b|rgba?\(\s*\d/g)) {
    errors.push(`${file}:${lineOf(src, m.index)} hard-coded colour "${m[0]}"; use var(--token)`);
  }
}

const html = read('index.html');
for (const sheet of ['styles/fonts.css', 'styles/tokens.css', 'styles.css']) {
  if (!html.includes(`href="${sheet}"`)) errors.push(`index.html must load ${sheet}`);
}
if (html.indexOf('href="styles/tokens.css"') > html.indexOf('href="styles.css"')) {
  errors.push('index.html must load styles/tokens.css before styles.css');
}
if (/fonts\.googleapis\.com|fonts\.gstatic\.com/.test(html)) errors.push('index.html must not load third-party fonts (blocked by the CSP)');

const fontsCss = read('styles/fonts.css');
const families = new Set();
for (const m of fontsCss.matchAll(/font-family:\s*'([^']+)'[\s\S]*?url\('\.\.\/(fonts\/[^']+)'\)/g)) {
  families.add(m[1]);
  if (!fs.existsSync(path.join(root, m[2]))) errors.push(`styles/fonts.css points at missing ${m[2]}`);
}
for (const family of families) {
  const licence = path.join(root, 'fonts', 'OFL-' + family.toLowerCase().replace(/\s+/g, '') + '.txt');
  if (!fs.existsSync(licence)) errors.push(`missing licence for ${family}: ${path.relative(root, licence)}`);
}
for (const family of ['DM Sans', 'DM Mono', 'Fraunces', 'Newsreader']) {
  if (!families.has(family)) errors.push(`styles/fonts.css must declare ${family}`);
}

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}
console.log(`Design token validation passed (${families.size} font families vendored).`);
